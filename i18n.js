function load() {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === "zh" || v === "en") return v;
  } catch { /* storage blocked — fall through to browser default */ }
  const nav = (typeof navigator !== "undefined" && navigator.language) ? navigator.language.toLowerCase() : "";
  return nav.startsWith("en") ? "en" : "zh";
}

let current = load();

export function getLang() { return current; }

export function setLang(lang) {
  current = lang === "en" ? "en" : "zh";
  try { localStorage.setItem(STORAGE_KEY, current); } catch { /* preference stays in memory */ }
  return current;
}

export function t(key, vars) {
  let s = (dict[current] && dict[current][key]) ?? dict.zh[key] ?? key;
  if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
  return s;
}

// 套用靜態 HTML 的翻譯：textContent / aria-label / placeholder，並設定 <html lang>。
export function applyStaticI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => { el.setAttribute("placeholder", t(el.dataset.i18nPh)); });
  document.documentElement.lang = t("localeTag");
  document.title = t("pageTitle");
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute("content", t("pageDescription"));
}
